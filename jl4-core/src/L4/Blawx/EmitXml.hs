-- | Render a 'BlawxDoc' to the Blockly XML that pairs with "L4.Blawx.Emit"'s
-- s(CASP) — the @xml_content@ side of every @blawx.workspace@ and
-- @blawx.blawxtest@ row (BLAWX-EXPORT-SPEC R12, phase P3).
--
-- __The fixpoint is the contract, and it runs the other way round.__
-- 'L4.Blawx.Emit.renderScasp' reproduces what @scasp_generator.js@ /would/
-- emit; this module emits the blocks that /make/ it emit that. The Blawx
-- editor regenerates @scasp_encoding@ from the deserialised blocks on every
-- save, so the chain that has to hold is
-- @textToDom → domToWorkspace → sCASP.workspaceToCode@ (@buttons.js:444-447@,
-- @:24@) landing back on the same bytes. Everything below is derived from the
-- block definitions (@blawx-blocks.js@), the mutation restorers
-- (@mutators.js@) and the generator (@scasp_generator.js@) at Blawx commit
-- @02eded1@; the per-block templates, with line citations for every claim, are
-- in @p3-design\/xml-plan.md@, and @etc\/blawx-fixpoint-harness.mjs@ executes
-- the chain headlessly.
--
-- Six facts shape everything here:
--
-- 1. __Top-level order is decided by @y@, not by document order.__
--    @workspaceToCode@ takes @getTopBlocks(true)@, sorted by
--    @y + sin(3°)·x@. Single-column layout with a strictly increasing @y@ is
--    therefore load-bearing, not cosmetic (spec §8.12's delegated
--    sub-decision).
-- 2. __A @[BBlock]@ stack is not one Blockly stack.__ @unattributed_fact@,
--    @unattributed_constraint@, @assume@, @attributed_rule@ and @query@ have
--    no @previousStatement@: they can only be roots, and @workspaceToCode@
--    joins roots with a blank line. Where a stack becomes several roots is
--    'L4.Blawx.IR.blockRuns', which "L4.Blawx.Emit" reads too — that is the
--    only way the blank lines in the two renderings can agree.
-- 3. __A failed connection type-check is silent__ in the XML path
--    (@Connection.connect@ returns a boolean that @domToBlockHeadless@
--    ignores): an incompatible child is created but left detached, becomes a
--    top-level block, and emits a spurious extra line. So every @check@ in
--    the block definitions is honoured here, and a goal that cannot satisfy
--    one is reported as an 'XmlGap' rather than emitted as XML that would
--    regenerate different bytes.
-- 4. __The checks are not all in the block definitions, and not all in the
--    mutators.__ @attributes.js@ — loaded by both editor templates
--    (@blawx.html:168@, @test.html:164@) and registered on @demoWorkspace@
--    (@attributes.js:21@) — reinstalls the connection checks of every
--    @attribute_selector@ on every @BLOCK_CREATE@, __with no @if
--    (attributeType)@ guard__ (contrast @mutators.js:165@). An absent or
--    empty @attributetype@ therefore does not mean \"no check\": it means
--    @blawxTypeToBlocklyType(\"\") === 'OBJECT'@. Under the @ov@ order the
--    /object/ slot is pinned to @['OBJECT','VARIABLE']@ unconditionally, and
--    @Connection.setCheck@ unplugs an already-connected incompatible child.
--    Measured: with @attributetype=\"\"@ six golden rows regenerated
--    differently (@[X | Rest].@ as its own naked top-level statement, and
--    @running_total(,)@ for the clause that lost both operands).
-- 5. __@\<mutation\>@ comes first__ and carries the predicate\/category names
--    the restorers read: several generator arms read a /mutation-restored
--    property/, never a field (@this.blawxAttributeName@, @this.arity@,
--    @block.section_reference@), so a missing mutation regenerates wrong code
--    or throws.
-- 6. __Menu-cache attributes (@category_list@, @attribute_list@,
--    @type_list@) are omitted__: every restorer that reads one has an
--    explicit reverse-compatibility branch, and a Blawx-authored example
--    ships without them.
--
-- __Slots with no structural choice.__ Three inputs are pinned to
-- @[OBJECT,VARIABLE]@ no matter what we write: @attribute_selector@'s object
-- slot (fact 4 — in /either/ argument order, so swapping does not help),
-- @unary_attribute_selector@'s @first_element@ (hardcoded in the JSON,
-- @blawx-blocks.js:3041-3048@, and its mutator never calls @setCheck@,
-- @mutators.js:181-195@) and @new_object_category@'s @object@. A list-valued
-- argument in one of those — @running_total([],0)@, @all_positive([X|Rest])@
-- — therefore has no /structural/ image anywhere in the 127-block inventory
-- (@relationship_selector@ starts at arity 3).
--
-- The answer is 'objectSlot': fall back to an @object_selector@ whose label
-- is the term's own s(CASP) text. Its output is @OBJECT@, so it survives
-- every pin; its field is a @field_label_serializable@ with no validator, so
-- it round-trips verbatim; and its generator arm is
-- @this.getFieldValue('object_name')@ (@scasp_generator.js:471-474@), so the
-- regenerated bytes are exactly the ones "L4.Blawx.Emit" wrote. What is lost
-- is /editability/ of that subterm in the UI, and only that — which is
-- strictly better than the alternative, a blank canvas whose Save deletes the
-- rule. The surrogate is used ONLY where the structural image would be torn
-- off; @[X | Rest]@ in a value slot still gets real @head_tail@ blocks, via
-- an @attributetype@ derived from the operand.
--
-- __Unrepresentable constructs.__ What the surrogate cannot rescue yields an
-- 'XmlGap' and an empty @xml_content@ rather than XML that would regenerate
-- different bytes. Such a row is a data-loss trap, not a neutral omission, so
-- the gaps are carried out to the CLI (@L4.Blawx.Emit.blawxXmlGaps@) and no
-- corpus golden is allowed to contain one.
module L4.Blawx.EmitXml
  ( -- * The renderer
    renderDocXml
  , BlawxXml (..)
    -- * What has no block image
  , XmlGap (..)
  , renderXmlGap
  ) where

