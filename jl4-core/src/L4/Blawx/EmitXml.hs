-- | The declarations' name fields carry @validate_predicate@
-- (@blawx-blocks.js:5216-5232@, installed at @:5129-5149@, @:5373@,
-- @:5255@), the sibling of the @validate_variable@ guarded in 'variableNode'.
-- It returns @null@ — leaving the field at its BLOCK DEFAULT — for a name
-- ending @_\\d+@ or containing anything outside @[\\w ]@, and lowercases the
-- initial otherwise. A rewritten declaration is worse than a rewritten
-- variable: every /selector/ reads its predicate from a mutation-restored
-- property rather than a field, so the call sites keep the real name while
-- the declaration regenerates @blawx_category(category_name)@ for a functor
-- nothing calls.
--
-- 'L4.Blawx.IR.mkBName' already enforces the invariant, so this cannot fire;
-- it is here so that a future regression in Lower's mangling surfaces as a
-- named gap instead of a silent rename.
predicateName :: Text -> BName -> Build Text
predicateName what nm
  | survivesPredicateValidator t = pure t
  | otherwise =
      gap (what <> " " <> t)
          "validate_predicate would silently rewrite this name to the field's default"
 where
  t = bNameText nm
  survivesPredicateValidator x = case Text.uncons x of
    Nothing -> False
    Just (c, cs) ->
      isAsciiLower c
        && Text.all wordChar cs
        && not (endsUnderscoreDigits x)
  wordChar c = isAsciiLower c || isAsciiUpper c || isDigit c || c == '_'
  endsUnderscoreDigits x =
    let ds = Text.takeWhileEnd isDigit x
    in  not (Text.null ds) && "_" `Text.isSuffixOf` Text.dropWhileEnd isDigit x

-- | @new_category_declaration@ — the one declaration with NO mutation
-- registered. @first_element@ is a fixed display label.
categoryDeclNode :: BCategoryDecl -> Build XNode
categoryDeclNode d = do
  nm <- predicateName "category" d.bcName
  pure $
    blockE
      "new_category_declaration"
      [ fieldE "category_name" nm
      , fieldE "prefix" d.bcPrefix
      , fieldE "first_element" "object"
      , fieldE "postfix" d.bcPostfix
      ]

-- | @new_attribute_declaration@. The mutation repeats @category_name@ and
-- @attribute_type@ because both dropdowns' static option lists are
-- placeholders: @domToMutation@ widens @menuGenerator_@ to the restored
-- value, and without that the later @\<field\>@ fails dropdown validation and
-- is silently discarded (the generator would then emit
-- @blawx_attribute(none,…)@).
attributeDeclNode :: BAttributeDecl -> Build XNode
attributeDeclNode d = do
  cat <- predicateName "category" d.baCategory
  nm  <- predicateName "attribute" d.baName
  pure $
    blockE
      "new_attribute_declaration"
      [ mutationE [("category_name", cat), ("attribute_type", ty)]
      , fieldE "category_name" cat
      , fieldE "attribute_name" nm
      , fieldE "attribute_type" ty
      , fieldE "order" order
      , fieldE "prefix" d.baPrefix
      , fieldE "first_element" firstEl
      , fieldE "infix" infixText
      , fieldE "second_element" secondEl
      , fieldE "postfix" d.baPostfix
      ]
 where
  ty = renderValueType d.baType
  boolean = case d.baType of BVBoolean -> True; _ -> False
  -- The block's own setOnChange forces order=ov and hides infix/second_element
  -- for a boolean attribute, and the generator's boolean arm reads neither
  -- (it synthesises the `not_applicable` atoms itself).
  order = if boolean then "ov" else renderNlgOrder d.baOrder
  infixText = if boolean then "" else d.baInfix
  (firstEl, secondEl) = case (boolean, d.baOrder) of
    (False, BOrderVO) -> ("value", "object")
    _                 -> ("object", "value")

-- | @relationship_declaration@ (the hand-written definition; the JSON of the
-- same name is superseded via @excluded_block_types@, and names the arity
-- field @arity@ where the real one — and the generator — say
-- @relationship_arity@).
--
-- @prefixI@\/@typeI@ must appear for every slot up to the arity, even when
-- the prefix is empty: for @I ≥ 4@ the restorer /creates/ the fields only if
-- @hasAttribute('prefix'+I)@.
relationshipDeclNode :: BRelationshipDecl -> Build XNode
relationshipDeclNode d
  | arity < 3 || arity > 10 =
      gap ("relationship " <> bNameText d.brName <> "/" <> Text.textShow arity)
          "relationship_declaration covers arity 3..10"
  | otherwise = do
      nm <- predicateName "relationship" d.brName
      pure $
        blockE
          "relationship_declaration"
          ( [ mutationE
                (concat [ [ ("prefix" <> Text.textShow i, pfx)
                          , ("type" <> Text.textShow i, renderValueType t)
                          ]
                        | (i, pfx, t) <- slots
                        ])
            , fieldE "relationship_name" nm
            , fieldE "relationship_arity" (Text.textShow arity)
            ]
              <> concat
                   [ [ fieldE ("prefix" <> Text.textShow i) pfx
                     , fieldE ("type" <> Text.textShow i) (renderValueType t)
                     ]
                   | (i, pfx, t) <- slots
                   ]
              <> [fieldE "postfix" d.brPostfix]
          )
 where
  arity = length d.brTypes
  slots = zip3 [1 :: Int ..] (d.brPrefixes <> repeat "") d.brTypes

