-- | A predicate application, dispatched by arity and by how the document
-- declares the predicate. Every arm's mutation carries the predicate name,
-- because that is where the generator reads it from.
predicateNode :: BlockSym -> BName -> [BTerm] -> Build XNode
predicateNode sym p args = case args of
  [] ->
    gap ("goal " <> n)
        "no Blawx block applies a zero-argument predicate"
  [a]
    | Set.member n sym.syCats -> do
        -- object_category + category_selector, NOT new_object_category.
        -- Both arms generate identical bytes (scasp_generator.js:311-316 vs
        -- :1161-1166, each @category(object)@), but new_object_category holds
        -- the category in a dropdown that updateLocalCategories rewrites
        -- (blawx-blocks.js:5586-5589 -> updateDropDownOptions snap-to-first).
        -- On the TEST editor page the workspace auto-load races window.onload
        -- populating knownCategories, so the dropdown is validated against an
        -- empty list and snapped, then re-snapped to the FIRST declared
        -- category — measured in the tier-2 UI drive: scores/q5 stored
        -- @student(b1)@ for our @basket(b1)@. category_selector is a
        -- field_label_serializable with no dropdown (blawx-blocks.js:752-765;
        -- restorer mutators.js:68-84), immune by construction. The race is
        -- upstream quirk #4, recorded in the spec.
        t <- objectSlot a
        pure $
          blockE
            "object_category"
            [ valueE "object" t
            , valueE "category" $
                blockE
                  "category_selector"
                  [ mutationE [("category_name", n)]
                  , fieldE "category_name" n
                  ]
            ]
    | otherwise -> do
        -- unary_attribute_selector's `first_element` hardcodes check
        -- [VARIABLE,OBJECT] (blawx-blocks.js:3041-3048) and its mutator never
        -- calls setCheck (mutators.js:181-195), so this is an objectSlot too.
        t <- objectSlot a
        let (pre, post, ty) = case Map.lookup n sym.syAttrs of
              Just d  -> (d.baPrefix, d.baPostfix, renderValueType d.baType)
              Nothing -> ("", n, "boolean")
        pure $
          blockE
            "unary_attribute_selector"
            -- attributename is MANDATORY (the generator reads
            -- this.blawxAttributeName); attributetype is inert here — the
            -- unary mutator stores it and performs no setCheck.
            [ mutationE [("attributename", n), ("attributetype", ty)]
            , fieldE "prefix" pre
            , fieldE "postfix" post
            , valueE "first_element" t
            ]
  [a, b] -> do
    -- Under attributeorder="ov" the OBJECT slot is `first_element` and the
    -- VALUE slot is `second_element`. attributes.js pins the object slot to
    -- [OBJECT,VARIABLE] whatever we write (module header fact 4), so that one
    -- is an objectSlot; the value slot's check is
    -- [blawxTypeToBlocklyType(attributetype),'VARIABLE'], which we choose to
    -- fit the operand.
    ta <- objectSlot a
    tb <- termNode b
    let decl = Map.lookup n sym.syAttrs
        -- attributetype selects the connection checks and nothing else (the
        -- generator never reads it). Prefer the declared type, but only when
        -- it admits the operand actually in the slot; otherwise derive the
        -- type from the operand. NEVER the empty string and never absent: ""
        -- is not "no check" (blawxTypeToBlocklyType("") === 'OBJECT'), and an
        -- absent attribute round-trips through mutationToDom as the literal
        -- "undefined", which is also OBJECT.
        ty = case decl of
          Just d | accepts [blocklyType d.baType, "VARIABLE"] b -> renderValueType d.baType
          _ -> inferredType b
        (pre, inf, post) = case decl of
          Just d  -> (d.baPrefix, d.baInfix, d.baPostfix)
          Nothing -> ("", n, "")
    pure $
      blockE
        "attribute_selector"
        -- attributeorder MUST be "ov": anything else (including an absent
        -- attribute, which reads as null) swaps the two operands.
        [ mutationE
            [("attributename", n), ("attributetype", ty), ("attributeorder", "ov")]
        , fieldE "prefix" pre
        , fieldE "infix" inf
        , fieldE "postfix" post
        , valueE "first_element" ta
        , valueE "second_element" tb
        ]
  _
    | arity > 10 ->
        gap (n <> "/" <> Text.textShow arity) "relationship_selector goes to arity 10"
    | otherwise -> do
        ts <- traverse termNode args
        let decl = Map.lookup n sym.syRels
            declTypes = maybe [] (\d -> d.brTypes) decl
            declPrefixes = maybe [] (\d -> d.brPrefixes) decl
            postfix = maybe "" (\d -> d.brPostfix) decl
            slotType i a = case drop (i - 1) declTypes of
              t : _ | accepts [blocklyType t, "VARIABLE"] a -> renderValueType t
              _ -> inferredType a
            prefixAt i = case drop (i - 1) declPrefixes of
              t : _ -> t
              [] | i == 1 -> n
                 | otherwise -> ""
            slots = zip [1 :: Int ..] args
        pure $
          blockE
            ("relationship_selector" <> Text.textShow arity)
            -- arity, relationship_name and type1..typeN are ALL mandatory:
            -- the restorer loops on arity, the generator reads
            -- this.relationship_name, and each typeI drives a setCheck.
            ( [ mutationE
                  ( [("arity", Text.textShow arity), ("relationship_name", n)]
                      <> [("type" <> Text.textShow i, slotType i a) | (i, a) <- slots]
                  )
              ]
                <> [fieldE ("prefix" <> Text.textShow i) (prefixAt i) | (i, _) <- slots]
                <> [fieldE "postfix" postfix]
                <> [valueE ("parameter" <> Text.textShow i) t | (i, t) <- zip [1 :: Int ..] ts]
            )
 where
  n = bNameText p
  arity = length args

