-- | Every row's Blockly XML, in the order the @.blawx@ stream stores them:
-- the workspaces, then the tests. Block @id@s are drawn from ONE
-- document-wide counter in that order, so the whole document is stable under
-- re-emission and two rows can never share an id (they are loaded into one
-- editor session by @drawers.js@).
--
-- A row with no blocks — and a row carrying a construct with no block image —
-- is the empty string, which is what the loader's truthiness guard
-- (@buttons.js:444@) expects and what the shipped @root_section@ of the
-- evidence example contains. Every gap is listed in 'bxGaps'.
data BlawxXml = MkBlawxXml
  { bxWorkspaces :: ![Text]     -- ^ one per 'BlawxDoc.bdWorkspaces' entry
  , bxTests      :: ![Text]     -- ^ one per 'BlawxDoc.bdTests' entry
  , bxGaps       :: ![XmlGap]   -- ^ why a row is empty, in row order
  }
  deriving stock (Eq, Show, Generic)
  deriving anyclass (NFData)

-- | One construct with no Blockly image, and the row it sank.
data XmlGap = MkXmlGap
  { xgRow  :: !Text   -- ^ workspace or test name (filled in by 'renderDocXml')
  , xgWhat :: !Text   -- ^ the construct, as text
  , xgWhy  :: !Text   -- ^ which block definition rules it out
  }
  deriving stock (Eq, Show, Generic)
  deriving anyclass (NFData)

renderXmlGap :: XmlGap -> Text
renderXmlGap g = g.xgRow <> ": " <> g.xgWhat <> " — " <> g.xgWhy

-- | The per-row @xml_content@ values. Rows are rendered in stream order with
-- a shared id counter; a gapped row consumes no ids, so ids stay stable when
-- an unrelated row gains or loses a gap.
renderDocXml :: BlawxDoc -> BlawxXml
renderDocXml doc =
  MkBlawxXml
    { bxWorkspaces = map value wsResults
    , bxTests      = map value testResults
    , bxGaps       = [g | Left g <- results]
    }
 where
  sym = documentSymbols doc
  rows =
    [ (renderSectionRef ws.bwName, ws.bwStacks) | ws <- doc.bdWorkspaces ]
      <> [ (t.btName, t.btStacks) | t <- doc.bdTests ]
  results = snd (mapAccumL step 1 rows)
  (wsResults, testResults) = splitAt (length doc.bdWorkspaces) results
  value = either (const "") id
  step :: Int -> (Text, [[BBlock]]) -> (Int, Either XmlGap Text)
  step i (name, stacks) = case build of
    Left g    -> (i, Left g {xgRow = name})
    Right rts ->
      let (i', numbered) = mapAccumL numberBlocks i rts
      in  (i', Right (rowText (layoutColumn numbered)))
   where
    build = do
      rts <- rowRoots sym stacks
      traverse_ representable rts
      pure rts

-- ---------------------------------------------------------------------------
-- Representability
-- ---------------------------------------------------------------------------

-- | Reject a row whose XML would carry a character XML 1.0 cannot express.
-- Dropping it silently is the one thing this module refuses to do anywhere
-- else — 'variableNode' and 'predicateName' turn a would-be silent rewrite
-- into an 'XmlGap' for exactly this reason — and a dropped control character
-- produces XML that deserialises cleanly and regenerates /different/ text.
--
-- Unreachable in this corpus ('L4.Blawx.Lower' sanitises every NLG slot), so
-- this is the guard being consistent, not a live bug.
representable :: XNode -> Build ()
representable = \case
  XText t -> check t
  XElem _ attrs kids -> traverse_ (check . snd) attrs *> traverse_ representable kids
 where
  check t = case Text.find unrepresentable t of
    Nothing -> pure ()
    Just c ->
      gap ("field text " <> Text.textShow t)
          ( "contains U+"
              <> Text.justifyRight 4 '0' (Text.pack (showHex (fromEnum c) ""))
              <> ", which XML 1.0 cannot represent even as a character reference" )

blockE :: Text -> [XNode] -> XNode
blockE ty kids = XElem "block" [("type", ty)] kids

-- | Every @\<mutation\>@ carries the xhtml namespace, as Blockly's serialiser
-- writes it (@document.createElement@ in the restorers puts the element in
-- the HTML namespace).
mutationE :: [(Text, Text)] -> XNode
mutationE attrs =
  XElem "mutation" (("xmlns", "http://www.w3.org/1999/xhtml") : attrs) []

fieldE :: Text -> Text -> XNode
fieldE name v = XElem "field" [("name", name)] [XText v]

valueE :: Text -> XNode -> XNode
valueE name b = XElem "value" [("name", name)] [b]

-- | A statement input. Emitted only when there is a block to put in it: an
-- empty @\<statement\>@ would be a hole the loader has to guess at, and the
-- generator's @getInputTargetBlock@ returns @null@ either way.
statementE :: Text -> Maybe XNode -> [XNode]
statementE name = foldMap (\b -> [XElem "statement" [("name", name)] [b]])

-- | Chain blocks the way Blockly does: each successor is the @\<next\>@ child
-- of its predecessor, and @\<next\>@ is the last child of a block.
chainBlocks :: [XNode] -> Maybe XNode
chainBlocks = foldr step Nothing
 where
  step b acc = Just (maybe b (\rest -> appendKid b (XElem "next" [] [rest])) acc)
  appendKid (XElem n as ks) k = XElem n as (ks <> [k])
  appendKid t _ = t

-- ---------------------------------------------------------------------------
-- Ids and layout
-- ---------------------------------------------------------------------------

-- | @Block@'s constructor takes any non-empty, non-duplicate id verbatim
-- (@this.id = c && !a.getBlockById(c) ? c : genUid()@), so ids are a
-- 9-character @l4b@ + zero-padded counter: deterministic (goldens are
-- stable), in a charset that needs no XML escaping, and — being 9 characters
-- where @genUid@ produces exactly 20 — incapable of colliding with a
-- Blockly-generated id on re-save.
numberBlocks :: Int -> XNode -> (Int, XNode)
numberBlocks i = \case
  XText t -> (i, XText t)
  XElem "block" attrs kids ->
    let (i', kids') = mapAccumL numberBlocks (i + 1) kids
    in  (i', XElem "block" (attrs <> [("id", blockId i)]) kids')
  XElem n attrs kids ->
    let (i', kids') = mapAccumL numberBlocks i kids
    in  (i', XElem n attrs kids')
 where
  blockId k = "l4b" <> Text.justifyRight 6 '0' (Text.textShow k)

-- | Single-column auto-layout (the delegated R12 sub-decision). Only
-- monotonicity in @y@ is load-bearing — @workspaceToCode@ sorts the top
-- blocks by @y + sin(3°)·x@, and a constant @x@ makes the second term vanish,
-- so the regenerated order equals our emission order. The pitch is legibility
-- only: enough vertical room for the rows the root actually draws.
layoutColumn :: [XNode] -> [XNode]
layoutColumn = go 40
 where
  go _ [] = []
  go y (r : rs) = place y r : go (y + 48 + 30 * blockRows r) rs
  place y (XElem n as ks) = XElem n (as <> [("x", "40"), ("y", Text.textShow (y :: Int))]) ks
  place _ t = t

-- | How many rows a root draws, for the pitch: the multi-input declaration
-- blocks and @attributed_rule@ render three rows apiece, everything else one.
blockRows :: XNode -> Int
blockRows = \case
  XElem "block" attrs kids -> weight (lookup "type" attrs) + sum (map blockRows kids)
  XElem _ _ kids -> sum (map blockRows kids)
  XText _ -> 0
 where
  weight ty
    | ty `elem` map Just tall = 3
    | otherwise = 1
  tall =
    [ "new_category_declaration"
    , "new_attribute_declaration"
    , "relationship_declaration"
    , "attributed_rule"
    ] :: [Text]

-- | The envelope. Newlines appear only between root @\<block\>@ elements (and
-- around them): @domToWorkspace@ skips non-element children of @\<xml\>@, so
-- that whitespace is inert — but a newline anywhere below a root would land
-- in a @\<field\>@'s @textContent@ and corrupt the field value. Never
-- pretty-print inside a block.
rowText :: [XNode] -> Text
rowText [] = ""
rowText roots =
  "<xml xmlns=\"https://developers.google.com/blockly/xml\">\n"
    <> Text.intercalate "\n" (map renderNode roots)
    <> "\n</xml>"

-- ---------------------------------------------------------------------------
-- The document's own symbol table
-- ---------------------------------------------------------------------------

-- | Which block a predicate goal becomes is keyed by arity and by how the
-- document declares the predicate, so the declarations are indexed first.
--
-- Undeclared predicates are normal and unavoidable (@member\/2@,
-- @running_total\/2@, the @findall@ generators): every selector's generator
-- arm reads its predicate name from a mutation-restored property, never from
-- a declaration, so the selectors work for them — only the UI's display text
-- degrades.
data BlockSym = MkBlockSym
  { syCats     :: !(Set Text)
  , syAttrs    :: !(Map Text BAttributeDecl)
  , syRels     :: !(Map Text BRelationshipDecl)
  , syDocName  :: !Text
    -- ^ the ruledoc name, for 'docPartLabel'\'s computed fallback
  , syDocParts :: !(Map BSectionRef Text)
    -- ^ 'L4.Blawx.IR.bdDocPartNames': the observed labels, when there are any
  }

documentSymbols :: BlawxDoc -> BlockSym
documentSymbols doc =
  MkBlockSym
    { syCats  = Set.fromList [bNameText d.bcName | BDeclareCategory d <- blocks]
    , syAttrs = Map.fromList [(bNameText d.baName, d) | BDeclareAttribute d <- blocks]
    , syRels  = Map.fromList [(bNameText d.brName, d) | BDeclareRelationship d <- blocks]
    , syDocName  = doc.bdName
    , syDocParts = doc.bdDocPartNames
    }
 where
  blocks = concat (concatMap (\ws -> ws.bwStacks) doc.bdWorkspaces)

