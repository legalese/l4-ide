-- | A term in a slot whose connection check is pinned to @[OBJECT,VARIABLE]@
-- and cannot be widened from the XML: @attribute_selector@'s object slot
-- (@attributes.js:8-15@, no @attributeType@ guard, and the @vo@ branch pins
-- the other input the same way, so the pin follows the /role/, not the
-- position), @unary_attribute_selector@'s @first_element@ and
-- @new_object_category@'s @object@.
--
-- A variable or an object atom goes in structurally. Anything else — in this
-- corpus, a list — would be created, rejected by the check, and left floating
-- as its own top-level block, which the generator then emits through
-- @scrubNakedValue@ as a spurious statement while the clause that lost it
-- regenerates with an empty argument. So the term goes in as an
-- @object_selector@ carrying its own s(CASP) text instead: same bytes out,
-- and the subterm is simply not editable in the UI. See the module header for
-- why there is no third option.
objectSlot :: BTerm -> Build XNode
objectSlot t
  | accepts ["OBJECT", "VARIABLE"] t = termNode t
  | otherwise = pure (objectSurrogate t)

objectSurrogate :: BTerm -> XNode
objectSurrogate t = objectSelectorNode (renderTerm t)

-- | @object_selector@: a mutation-restored @objectname@ (@mutators.js:52,57@)
-- and a @field_label_serializable@ the generator returns verbatim
-- (@scasp_generator.js:471-474@). The field carries NO validator, so whatever
-- text goes in comes back out.
objectSelectorNode :: Text -> XNode
objectSelectorNode t =
  blockE "object_selector" [mutationE [("objectname", t)], fieldE "object_name" t]

termNode :: BTerm -> Build XNode
termNode = \case
  BTVar v  -> variableNode v
  BTNum q
    | denominator q == 1 -> pure (numberNode (numerator q))
    | otherwise ->
        gap ("number " <> renderRationalText q)
            "number_value holds one field_number, never a ratio; term position \
            \has no slot for a math_operation"
  BTAtom a -> pure (objectSelectorNode (bNameText a))
  BTNil -> pure (blockE "empty_list" [])
  BTCons h t -> do
    hd <- termNode h
    tl <- termNode t
    pure (blockE "head_tail" [valueE "head" hd, valueE "tail" tl])

-- | @variable@ carries the @validate_variable@ field validator, which runs on
-- deserialisation and — for anything that is not @^[A-Za-z][\\w ]*$@, or that
-- ends @_\\d+@ — returns @null@, silently keeping the block's default @A@. It
-- also uppercases the initial and turns spaces into underscores. So the only
-- variable text that survives a load unchanged is an uppercase-initial word
-- character run not ending in @_\\d+@; anything else is a silent rename, and
-- is reported as a gap instead.
variableNode :: BVar -> Build XNode
variableNode v
  | survivesValidator t = pure (blockE "variable" [fieldE "variable_name" t])
  | otherwise =
      gap ("variable " <> t)
          "validate_variable would silently rewrite this name to \"A\""
 where
  t = varText v
  survivesValidator x = case Text.uncons x of
    Nothing -> False
    Just (c, cs) ->
      isAsciiUpper c
        && Text.all wordChar cs
        && not (endsUnderscoreDigits x)
  wordChar c = isAsciiLower c || isAsciiUpper c || isDigit c || c == '_'
  endsUnderscoreDigits x =
    let ds = Text.takeWhileEnd isDigit x
    in  not (Text.null ds) && "_" `Text.isSuffixOf` Text.dropWhileEnd isDigit x

varText :: BVar -> Text
varText (MkBVar t) = t

-- | @number_value@'s @field_number@ has no @min@, no @max@ and no
-- @precision@, and the generator string-concatenates the JS number, so an
-- integral value prints with no decimal point and a negative sign lives
-- inside the field.
numberNode :: Integer -> XNode
numberNode i = blockE "number_value" [fieldE "value" (Text.textShow i)]

-- | Arithmetic. Structural, one @math_operation@ per binary node, matching
-- 'L4.Blawx.Emit'\'s @renderArith@ image @( l op r )@ layer for layer.
arithNode :: BArith -> Build XNode
arithNode = \case
  BANum q -> numberOrRatio q
  BAVar v -> variableNode v
  BANeg (BANum q) -> numberOrRatio (negate q)
  BANeg e -> do
    r <- arithNode e
    pure (mathOp "sub" (numberNode 0) r)
  BABin op l r -> do
    a <- arithNode l
    b <- arithNode r
    pure (mathOp (opField op) a b)
 where
  numberOrRatio q
    | denominator q == 1 = pure (numberNode (numerator q))
    -- The R7-gated non-integral arm: its only block image is a division of
    -- two number_value fields, which is exactly Emit.renderArithNum's
    -- @( num / den )@.
    | otherwise = pure (mathOp "div" (numberNode (numerator q)) (numberNode (denominator q)))
  mathOp op l r =
    blockE
      "math_operation"
      [fieldE "operator" op, valueE "left_side" l, valueE "right_side" r]
  opField = \case
    BAdd -> "add"
    BSub -> "sub"
    BMul -> "mul"
    BDiv -> "div"

-- | The Blockly output type of an arithmetic expression's block: everything
-- but a bare variable is @Number@.
arithOutput :: BArith -> Text
arithOutput = \case
  BAVar _ -> "VARIABLE"
  _       -> "Number"

-- ---------------------------------------------------------------------------
-- Labels for gap messages
-- ---------------------------------------------------------------------------

termLabel :: BTerm -> Text
termLabel = \case
  BTVar v    -> varText v
  BTNum q    -> renderRationalText q
  BTAtom a   -> bNameText a
  BTNil      -> "[]"
  BTCons h t -> "[" <> termLabel h <> " | " <> termLabel t <> "]"

arithLabel :: BArith -> Text
arithLabel = \case
  BANum q      -> renderRationalText q
  BAVar v      -> varText v
  BANeg e      -> "-" <> arithLabel e
  BABin _ l r  -> "(" <> arithLabel l <> " . " <> arithLabel r <> ")"

renderRationalText :: Rational -> Text
renderRationalText q
  | denominator q == 1 = Text.textShow (numerator q)
  | otherwise = Text.textShow (numerator q) <> "/" <> Text.textShow (denominator q)
