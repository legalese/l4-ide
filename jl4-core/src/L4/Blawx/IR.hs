-- | A 'Rational' in __term__ position (the @number_value@ block plugged into
-- an attribute or relationship selector). An integral one renders as its
-- integer text — the @field_number@'s JS number, which carries no decimal
-- point (@blawx-blocks.js:924-938@; no @min@, no @precision@, so negatives
-- and decimals are both admissible field values).
--
-- A non-integral one renders @num\/den@, which is __not__ a @number_value@
-- image: the field holds one number, never a ratio, and term position has no
-- other slot to put a @math_operation@ in. The arm is totality, not policy —
-- Lower's R7 gate rejects non-integral literals with a named diagnostic — and
