-- | The __block-level__ intermediate representation of a Blawx project: one
-- 'BlawxDoc' per L4 module, modelling Blawx's /block/ inventory — categories,
-- attributes, relationships, attributed rules, facts, constraints, abducibles,
-- queries — and never s(CASP) text. Blocks are the pivot because they are the
-- only representation from which __both__ wire formats derive
-- (BLAWX-EXPORT-SPEC R12): the server stores @scasp_encoding@ and
-- @xml_content@ verbatim and derives neither from the other; only the block
-- structure determines both.
--
-- __The two-renderer contract.__ Both renderers consume this IR and nothing
-- else:
--
--   * @L4.Blawx.Emit.renderScasp :: BlawxDoc -> Text@ — P1; byte-exact
--     against @scasp_generator.js@ at Blawx commit @02eded1@, quirks included
--     (R10), because the fidelity gate is the re-save fixpoint: the Blawx
--     editor regenerates @scasp_encoding@ from blocks on every save, and the
--     stored text must not change (R12).
--   * @L4.Blawx.EmitXml.renderDocXml :: BlawxDoc -> BlawxXml@ — P3; the
--     paired Blockly XML, i.e. the blocks that make that regeneration land on
--     those bytes. Its per-row texts are what @renderBlawxYaml@ stores as
--     @xml_content@, and its @bxGaps@ are the rows it could not image.
--
-- The two are written against the same evidence from opposite ends, so a
-- change to either without the other breaks the fixpoint silently. The
-- structural names they must spell identically ('renderSectionRef',
-- 'renderValueType', 'renderNlgOrder', 'renderTerm') therefore live here
-- rather than in either emitter — as does 'blockRuns', which decides where a
-- stack becomes two Blockly roots and so where @renderScasp@ must put a blank
-- line.
--
-- Anything expressible in this IR must therefore be expressible as /blocks/:
-- a constructor with no block image (e.g. a raw Prolog escape hatch) must not
-- be added, because @renderScasp@ could print it but the XML could not, and
-- the first UI save would destroy it.
--
-- __That is necessary, not sufficient__: an image can also be missing for a
-- /combination/ of constructor and argument sort that each have images
-- separately. The witness is a binary predicate whose first argument is a
-- list: @attribute_selector@'s object slot is pinned to @[OBJECT,VARIABLE]@
-- by @attributes.js@ in /both/ argument orders, so @running_total([],0)@ has
-- no structural image even though @BFact@, @BTNil@ and @BTNum@ all do.
-- "L4.Blawx.EmitXml" answers such a slot with a verbatim @object_selector@
-- surrogate where it can (the generated bytes are then exact and the subterm
-- is merely not editable in the UI) and with an @XmlGap@ where it cannot.
--
-- __The P5 import-pivot role.__ The import direction (R14, @l4 blawx
-- --import@) parses @xml_content@ into /this same IR/ (@L4.Blawx.Parse@) and
-- lifts it to L4 (@L4.Blawx.Lift@); @scasp_encoding@ is only a cross-check —
-- regenerate via @renderScasp@ and diff to detect stale or hand-edited
-- encodings before lifting. The round-trip property @lift . emit = id@
-- (modulo formatting) on the v1 export fragment is stated against this type.
-- Consequently the IR must stay faithful to what blocks /store/ (e.g. NLG
-- prefix\/infix\/postfix as three separate fields, not a fused sentence),
-- or the fixpoint and the import both lose information.
--
-- __Names are already target-lexical here.__ "L4.Blawx.Lower" mangles
-- 'L4.Relational.IR.RName's into 'BName's (@^[a-z]\\w*$@, not ending
-- @_\\d+@ — the UI validator silently rewrites violations) and runs the
-- injective collision check /before/ building the 'BlawxDoc'; the emitters
-- never mangle. Provenance for citations rides along as the original
-- 'Unique'\/'SrcRange' so P4's justification story and the goldens' error
-- messages can still point at L4 source.
