-- | Render a 'DAPackage' to a single self-contained docassemble interview
-- (YAML). Output is built as plain @[Text]@ + 'Text.unlines' (never a @Doc@)
-- so indentation is exact and golden-stable — doubly binding here, because
-- YAML is indentation-sensitive and docassemble splits the file into blocks
-- with a whole-line regex /before/ YAML parsing.
--
-- Emission hygiene (spec R9), all enforced by construction in this module:
--
--   1. Every L4-derived string passes through the one escape function
--      'escapeL4' (Mako @${@, @<%@, @</%@, line-leading @%@ and @##@ — every
--      escape is itself a Mako compile trigger, so the escaped text renders
--      identically whether or not docassemble compiles it), and inline YAML
--      scalars are additionally double-quoted via 'yamlStr'.
--   2. Prose lands only inside block scalars whose every line is indented two
--      spaces ('blockScalar'), so no generated line can ever match
--      docassemble's block-splitting regex @^--- *$@ (@parse.py:138@).
--   3. Top-level keys are lower-case only and drawn from the vendored
--      whitelist 'daRecognisedKeys' — docassemble silently ignores unknown
--      keys, so 'emitterVocabularyViolations' exists for a test to assert
--      empty.
--   4. Every @code:@ block carries a deterministic @id:@, explicit @sets:@,
--      and @depends on:@ over its direct inputs (docassemble variables are
--      otherwise stale-by-default).
--   5. Emitted Python never builds an eager list to fold over. @and@/@or@
--      chains short-circuit natively, and M4's @all@/@any@ over a gathered
--      @DAList@ take a GENERATOR — @all(p(x) for x in xs)@, never
--      @all([p(x) for x in xs])@ — so a decided quantifier stops reading
--      elements, and the questions of the elements after it are never asked.
--   6. The mandatory driver is idempotent — pure references and conditionals
--      — and never wraps exceptions; @mandatory:@ is never mixed with
--      @initial:@; every directive block carries @question:@.
module L4.Docassemble.Emit
  ( renderPackage
  , renderPackageTree
  , packageSlug
  , escapeL4
  , emitterKeyVocabulary
  , emitterBlockKeys
  , emitterFieldModifiers
  , emitterAttachmentKeys
  , daRecognisedKeys
  , emitterVocabularyViolations
  ) where

import Base
