-- | The mandatory driver. Its first statement, when the module cites anything,
-- is a bare reference to the citation-reset sentinel: docassemble seeks it,
-- runs its block (which empties the explanation list), and only then does the
-- driver reach the goal that pulls the rules. Reference-before-goal is the
-- whole mechanism, so the two must not be reordered.
driverLines :: Maybe Text -> DADriver -> [Text]
driverLines mFresh = \case
  DASeamDriver did goalL4 scopeV reqV verdictV evC evI evN ->
       [ "id: " <> did
       , "mandatory: True"
       , "reconsider: True"
       , "code: |"
       ]
    <> map ("  " <>) freshLines
    <> map ("  " <>)
       [ "# verdict driver for @export `" <> escapeL4 goalL4 <> "` — scope-first (R4)."
       , "# Never `not scope or requirement`: NotApplicable is not Complies."
       , "if " <> scopeV <> ":"
       , "    if " <> reqV <> ":"
       , "        " <> verdictV <> " = 'Complies'"
       , "        " <> evC
       , "    else:"
       , "        " <> verdictV <> " = 'InBreach'"
       , "        " <> evI
       , "else:"
       , "    " <> verdictV <> " = 'NotApplicable'"
       , "    " <> evN
       ]
    <> [ "sets:"
       , "  - " <> verdictV
       ]
  DABoolDriver did goalL4 goalV evH evF ->
       [ "id: " <> did
       , "mandatory: True"
       , "reconsider: True"
       , "code: |"
       ]
    <> map ("  " <>) freshLines
    <> map ("  " <>)
       [ "# driver for @export `" <> escapeL4 goalL4 <> "`"
       , "if " <> goalV <> ":"
       , "    " <> evH
       , "else:"
       , "    " <> evF
       ]
  DAValueDriver did goalL4 goalV evR ->
       [ "id: " <> did
       , "mandatory: True"
       , "reconsider: True"
       , "code: |"
       ]
    <> map ("  " <>) freshLines
    <> map ("  " <>)
       [ "# driver for @export `" <> escapeL4 goalL4 <> "`"
       , goalV
       , evR
       ]
 where
  freshLines =
    [ ln
    | Just v <- [mFresh]
    , ln <- [ "# spec §8.4: pull the citation reset BEFORE the goal, so the"
            , "# explanation list is emptied before any rule re-explains into it."
            , v
            ]
    ]

screenLines :: Maybe DAAttachment -> DAScreen -> [Text]
screenLines mAttach s =
     [ "id: " <> s.sId
     , "event: " <> s.sEvent
     , "question: |"
     ]
  <> blockScalar (escapeL4 s.sGoalL4 <> ": " <> s.sVerdict)
  <> [ "subquestion: |" ]
  <> blockScalar subBody
 where
  subBody =
       maybe "" (\d -> escapeL4 d <> "\n\n") s.sDesc
    <> s.sExplain
    <> maybe "" (\v -> "\n\n**${ " <> v <> " }**") s.sShowVar
    <> citationSection
    <> documentSection
  -- M4: the verdict screen hands back the document as well as the answer.
  -- Referencing it here is what makes docassemble assemble it at all, and
  -- `${ <var> }` on a DAFileCollection renders its download links.
  documentSection = case mAttach of
    Nothing -> ""
    Just a  -> "\n\nYour document:\n\n${ " <> a.atVar <> " }"
  -- M2. The docassemble house pattern, copied from the canonical exhibit
  -- `docassemble_demo/…/examples/explain.yml` at 1b6678384: a Mako `% for`
  -- over `logic_explanation()`. The control line is legal here because
  -- 'blockScalar' indents every line by exactly two spaces and YAML strips
  -- that indentation, so Mako sees `% for` in column 1.
  --
  -- Rendering rather than inlining is also what makes the R9.1 escaping claim
  -- honest for citations: the citation text is interpolated into the output
  -- stream at render time and is never re-read as Mako, so a `%`-leading or
  -- `${ … }`-bearing citation reaches the screen verbatim.
  citationSection
    | s.sCites =
        "\n\nWhy this answer — the rules that actually decided it:\n\n\
        \% for citation in logic_explanation():\n\
        \* ${ citation }\n\
        \% endfor"
    | otherwise = ""

-- | M4: the assembled letter (spec §10's document-assembly demo).
--
-- A STANDALONE block, not one hung off the verdict screen: the document is a
-- definition like any other, sought when the screen references
-- @${ \<variable name\> }@, and keeping it separate keeps the screen's prose out
-- of the attachment's own key space (attachment sub-keys are a third
-- vocabulary, 'emitterAttachmentKeys', read by @process_attachment@ rather than
-- by the block-key loop — and an unrecognised one is ignored in silence).
--
-- The SINGULAR mapping form, not a list of attachments: one document, one
-- variable to assert about.
--
-- @content:@ is INLINE rather than @content file:@ on purpose: @content file@
-- resolves through @package_template_filename@ and raises @DASourceError@ when
-- the file is not found (@parse.py:5059-5064@) — at PARSE time, before any
-- question is asked — which would make the bare single-file artifact
-- unloadable while the packaged one worked. The template still ships in the
-- @--package@ tree, under @data\/templates@, as provenance.
--
-- @valid formats: [html]@ and nothing else: the harness venv has @docx@ and
-- @docxtpl@ but no LibreOffice, so a PDF format would fail at assemble time.
attachmentLines :: DAAttachment -> [Text]
attachmentLines a =
     [ "id: attachment_" <> a.atVar
     , "attachment:"
     , "  name: " <> yamlStr (escapeL4 a.atName)
     , "  filename: " <> yamlStr a.atFile
     -- Without `variable name:` docassemble files the document under
     -- `_internal['docvar'][n]` (parse.py:4997-5003) and nothing can assert
     -- about it afterwards — and the failure worth catching is not an exception
     -- but a SUCCESSFUL EMPTY RENDER, which raises nothing and logs nothing.
     , "  variable name: " <> a.atVar
     , "  valid formats:"
     , "    - html"
     , "  content: |"
     ]
  -- Verbatim, and indented four spaces: it is the author's own Mako, written to
  -- be rendered (R9.1 escapes L4-derived prose, which this is not). The indent
  -- also keeps every line clear of docassemble's `^--- *$` block splitter.
  <> [ if Text.null ln then "" else "    " <> ln | ln <- Text.splitOn "\n" (Text.stripEnd a.atContent) ]

-- | M4: the compliance checklist (spec §10).
--
-- Rows are @note:@s carrying @showifdef@, and that is the only recipe that
-- works. @skip undefined: False@ FORCE-ASKS every undefined row
-- (@parse.py:5876-5904@ stops wrapping the row's eval in try/except), and the
-- default silently drops undefined rows into a debug log line — one
-- interrogates the user about questions the law never reached, the other hides
-- them. A @note:@ row has no @saveas@ to evaluate, so it renders either way.
reviewLines :: DAReview -> [Text]
reviewLines rv =
     [ "id: " <> rv.rvId
     , "event: " <> rv.rvEvent
     , "question: |"
     ]
  <> blockScalar rv.rvTitle
  <> [ "review:" ]
  <> concatMap rowLines rv.rvRows
 where
  rowLines r =
    [ "  - note: |"
    , "      " <> escapeL4 r.rrLabel <> ": ${ showifdef("
        <> pyStr r.rrVar <> ", '**not asked**') }"
    ]

-- ---------------------------------------------------------------------------
-- Escaping (R9.1) and scalar rendering
-- ---------------------------------------------------------------------------

-- | THE escape function: every L4-derived string passes through here before
-- reaching any Mako-rendered position.
--
-- The invariant is /render-identity under both fates/: docassemble only
-- Mako-compiles a string when @match_mako@ fires (@parse.py:135@:
-- @<%|\\${|% if|% for|% while|##@ — a @TextObject@ without a match keeps the
-- text verbatim), so every escape sequence must itself be a compile trigger
-- and must render back to exactly the original text. Each Mako-significant
-- span is therefore rewritten to the Mako expression that prints it —
-- @${'…'}@ contains @${@, so an escaped string always compiles, and a string
-- we did not touch renders verbatim uncompiled:
--
--   * @${@   → @${'${'}@   (a backslash is NOT an escape in the vendored
--     @docassemble_mako@ — @\\${ x }@ still evaluates @x@; probed at 1.10.7);
--   * @<%@   → @${'<%'}@   (an unclosed @<%@ otherwise fails the WHOLE
--     interview at parse time, and a closed @<%x%>@ span is silently
--     swallowed; a bare @%>@ with no opening tag renders as plain text);
--   * @</%@  → @${'</%'}@  (a closing tag without an opening tag is a
--     @SyntaxException@ under compilation);
--   * line-leading @[ \\t]*%@ → @${'%'}@ for the @%@ (the vendored
--     control-line regex admits leading blanks; the former @%%@ doubling
--     only rendered as @%@ when something ELSE triggered compilation, and
--     otherwise reached the user verbatim as @%%@);
--   * line-leading @[ \\t]*##@ → @${'##'}@ (a compiled line-leading @##@ is
--     a Mako comment: the line would vanish from the prose).
--
-- YAML-significant leaders are neutralised by context: inline scalars go
-- through 'yamlStr' (double-quoted), prose goes through 'blockScalar' (every
-- line indented).
escapeL4 :: Text -> Text
escapeL4 t =
  Text.intercalate "\n"
    (map guardLine (Text.splitOn "\n" spans))
 where
  -- Order matters only in that the replacements must not rescan each
  -- other's output; none of the inserted texts contains a later pattern.
  spans =
      Text.replace "</%" "${'</%'}"
    . Text.replace "<%"  "${'<%'}"
    . Text.replace "${"  "${'${'}"
    $ t
  guardLine ln =
    let (ws, rest) = Text.span (\c -> c == ' ' || c == '\t') ln
    in case () of
         _ | Just rest' <- Text.stripPrefix "##" rest -> ws <> "${'##'}" <> rest'
           | Just rest' <- Text.stripPrefix "%" rest  -> ws <> "${'%'}" <> rest'
           | otherwise                                -> ln

-- | A double-quoted YAML scalar: nothing inside can be misread as YAML
-- syntax, a boolean, or a block-structure leader.
yamlStr :: Text -> Text
yamlStr t = "\"" <> Text.concatMap esc t <> "\""
 where
  esc '"'  = "\\\""
  esc '\\' = "\\\\"
  esc '\n' = "\\n"
  esc ch   = Text.singleton ch

-- | Block-scalar content, every non-empty line indented two spaces so no
-- generated prose line can match docassemble's @^--- *$@ block splitter
-- (R9.7). Empty lines stay empty (blank lines inside a block scalar are
-- legal and cannot match the splitter).
blockScalar :: Text -> [Text]
blockScalar t =
  [ if Text.null ln then "" else "  " <> ln | ln <- Text.splitOn "\n" t ]

-- ---------------------------------------------------------------------------
-- Python expression rendering
-- ---------------------------------------------------------------------------

-- | Fully parenthesised, so Python precedence can never disagree with the
-- L4 AST; operand order is preserved because operand order is question order
-- (CPython short-circuit is the pruner, spec §2).
renderPyExpr :: DAExpr -> Text
renderPyExpr = go
 where
  go = \case
    DANum r      -> renderNum r
    DAStrLit t   -> pyStr t
    DABoolLit b  -> if b then "True" else "False"
    DAVar v      -> v
    DABin op a b -> paren (go a <> " " <> binOp op <> " " <> go b)
    DACmp op a b -> paren (go a <> " " <> cmpOp op <> " " <> go b)
    DAAnd a b    -> paren (go a <> " and " <> go b)
    DAOr a b     -> paren (go a <> " or " <> go b)
    DANot a      -> paren ("not " <> go a)
    DACond c t e -> paren (go t <> " if " <> go c <> " else " <> go e)
    DAIsNone a   -> paren (go a <> " is None")
    DAIsBool a b -> paren (go a <> " is " <> (if b then "True" else "False"))
    DADateLit iso -> "as_datetime(" <> pyStr iso <> ")"
    DAAttr a f   -> go a <> "." <> f
    DAMethod a m kws ->
      go a <> "." <> m <> "("
        <> Text.intercalate ", " [ k <> "=" <> go v | (k, v) <- kws ] <> ")"
    -- A generator expression, deliberately not a list comprehension: `all`
    -- stops at the first false element, so the elements after it are never
    -- read and their questions are never asked.
    DAQuant op v lst body ->
      quantName op <> "(" <> go body <> " for " <> v <> " in " <> go lst <> ")"
  quantName = \case
    DAAll -> "all"
    DAAny -> "any"
  binOp = \case
    DAAdd -> "+"; DASub -> "-"; DAMul -> "*"; DADiv -> "/"; DAMod -> "%"
  cmpOp = \case
    DALt -> "<"; DALeq -> "<="; DAGt -> ">"; DAGeq -> ">="; DAEq -> "=="; DANeq -> "!="

paren :: Text -> Text
paren t = "(" <> t <> ")"

-- | A Python single-quoted string literal with minimal escaping.
pyStr :: Text -> Text
pyStr t = "'" <> Text.concatMap esc t <> "'"
 where
  esc '\\' = "\\\\"
  esc '\'' = "\\'"
  esc '\n' = "\\n"
  esc ch   = Text.singleton ch

-- | Render a rational as a clean Python numeric literal (the OpenFisca
-- 'renderNum' discipline): integers print bare; fractions that terminate in
-- base 10 print as decimals; anything else prints as an exact division so no
-- precision is silently lost at emission time.
renderNum :: Rational -> Text
renderNum r
  | d == 1    = sign <> tshow (abs n)
  | otherwise = case terminating (abs n) d of
      Just t  -> sign <> t
      Nothing -> "(" <> tshow n <> " / " <> tshow d <> ")"
 where
  n    = numerator r
  d    = denominator r
  sign = if n < 0 then "-" else ""

terminating :: Integer -> Integer -> Maybe Text
terminating num den =
  let places = countFactors 2 den `max` countFactors 5 den
  in if stripFactors 5 (stripFactors 2 den) == 1
       then Just (format places (num * (10 ^ places) `div` den))
       else Nothing
 where
  countFactors p = goC (0 :: Integer)
    where goC acc y | y `mod` p == 0 && y /= 0 = goC (acc + 1) (y `div` p)
                    | otherwise                = acc
  stripFactors p y | y `mod` p == 0 && y /= 0 = stripFactors p (y `div` p)
                   | otherwise                = y
  format places scaled
    | places == 0 = tshow scaled
    | otherwise =
        let s             = Text.justifyRight (fromIntegral places + 1) '0' (tshow scaled)
            (whole, frac) = Text.splitAt (Text.length s - fromIntegral places) s
        in whole <> "." <> frac

tshow :: Show a => a -> Text
tshow = Text.pack . show

