-- | A TOML basic string.
tomlStr :: Text -> Text
tomlStr t = "\"" <> Text.concatMap esc t <> "\""
 where
  esc '"'  = "\\\""
  esc '\\' = "\\\\"
  esc '\n' = "\\n"
  esc ch   = Text.singleton ch

-- | Text safe to splice into a TOML @#@ comment: a comment runs to end of line,
-- so any line break in it escapes the comment and the next line is read as
-- TOML. A POSIX filename may contain a newline, and the source basename is
-- spliced into the generated @pyproject.toml@ header verbatim — with
-- @$'a\\n[project]\\nb.l4'@ that header emitted a bare @[project]@ table on its
-- own line and @tomllib@ refused the file, while @l4 docassemble --package@
-- reported success and exit 0. Every /other/ consumer of this string was
-- already escaped by position ('tomlStr' for @description@, 'pyStr' for
-- @L4_SOURCE_NAME@, the percent-encoded @pkgSource@ in the interview header);
-- this closes the one hole. Control characters become spaces rather than
-- vanishing, so the comment still shows that something unusual was there.
tomlComment :: Text -> Text
tomlComment = Text.map \ch -> if ch < ' ' || ch == '\DEL' then ' ' else ch

